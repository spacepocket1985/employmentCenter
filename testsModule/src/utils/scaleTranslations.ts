  pay: 'Зарплата',
  promotion: 'Продвижение',
  supervision: 'Руководство',
  benefits: 'Бонусы',
  rewards: 'Поощрения',
  conditions: 'Условия работы',
  coworkers: 'Коллеги',
  nature: 'Содержание работы',
  communication: 'Коммуникация',

  // Шкалы JAS (Шкала тревоги на рабочем месте)
