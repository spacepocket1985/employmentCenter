/**
 * Функция для перевода названия шкалы
 * @param scaleId - Идентификатор шкалы (например, 'pay')
 * @returns Переведённое название или оригинал, если перевод не найден
 */
export const translateScale = (scaleId: string): string => {
  return scaleTranslations[scaleId] || scaleId;
};
